DEFINE_LOG_CATEGORY_STATIC(LogAttributeWidgetExport, Log, All);

namespace
{
	// Children first: a panel that nests another WBP constructs it from its (already exported) class
	const TCHAR* const AttributeWidgetBlueprints[] = {
		TEXT("/Game/AttributeSample/UI/WBP_AttributeAssetItem"),
		TEXT("/Game/AttributeSample/UI/WBP_AttributeList"),
		TEXT("/Game/AttributeSample/UI/WBP_AttributeAssetList"),
		TEXT("/Game/AttributeSample/UI/WBP_LeftPanel"),
		TEXT("/Game/AttributeSample/UI/WBP_RightPanel"),
	};

	// Writing a tree into a Widget Blueprint: close editors, clear, set variables, compile, save.
	namespace WidgetWriter
	{
		void CloseEditors(UWidgetBlueprint* Blueprint)
		{
			if (GEditor && Blueprint)
			{
				if (UAssetEditorSubsystem* AssetEditors = GEditor->GetEditorSubsystem<UAssetEditorSubsystem>())
				{
					AssetEditors->CloseAllEditorsForAsset(Blueprint);
				}
			}
		}

		// True when the tree has more than the factory's empty root panel.
		bool HasDesignerContent(const UWidgetBlueprint* Blueprint)
		{
			const UWidget* Root = Blueprint && Blueprint->WidgetTree ? Blueprint->WidgetTree->RootWidget.Get() : nullptr;
			if (!Root)
			{
				return false;
			}
			const UPanelWidget* RootPanel = Cast<UPanelWidget>(Root);
			return !RootPanel || RootPanel->GetChildrenCount() > 0;
		}

		void ClearTree(UWidgetBlueprint* Blueprint)
		{
			UWidgetTree* Tree = Blueprint->WidgetTree;
			TArray<UWidget*> OldWidgets;
			Tree->GetAllWidgets(OldWidgets);
			Tree->RootWidget = nullptr;
			for (UWidget* Widget : OldWidgets)
			{
				Widget->Rename(nullptr, GetTransientPackage(), REN_DontCreateRedirectors | REN_NonTransactional);
				Widget->MarkAsGarbage();
			}
			// Regenerated by the compiler for the new widgets
			Blueprint->WidgetVariableNameToGuidMap.Empty();
		}

		// First native class in the parent chain.
		UClass* GetNativeParent(const UWidgetBlueprint* Blueprint)
		{
			UClass* Class = Blueprint ? Blueprint->ParentClass.Get() : nullptr;
			while (Class && !Class->HasAnyClassFlags(CLASS_Native))
			{
				Class = Class->GetSuperClass();
			}
			return Class;
		}

		// Widgets named like a BindWidget / BindWidgetOptional property become variables.
		void MarkBoundWidgetsAsVariables(UWidgetBlueprint* Blueprint)
		{
			TSet<FName> Bound;
			if (const UClass* Native = GetNativeParent(Blueprint))
			{
				for (TFieldIterator<FObjectPropertyBase> It(Native); It; ++It)
				{
					if (It->HasMetaData(TEXT("BindWidget")) || It->HasMetaData(TEXT("BindWidgetOptional")))
					{
						Bound.Add(It->GetFName());
					}
				}
			}
			Blueprint->WidgetTree->ForEachWidget([&Bound](UWidget* Widget)
			{
				Widget->SetFlags(RF_Transactional);
				Widget->bIsVariable = Bound.Contains(Widget->GetFName());
			});
		}

		bool CompileAndSave(UWidgetBlueprint* Blueprint, FString& OutError)
		{
			FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint);
			FKismetEditorUtilities::CompileBlueprint(Blueprint);
			if (Blueprint->Status == BS_Error)
			{
				OutError = FString::Printf(TEXT("%s did not compile"), *Blueprint->GetName());
				return false;
			}
			if (!UEditorLoadingAndSavingUtils::SavePackages({ Blueprint->GetPackage() }, false))
			{
				OutError = FString::Printf(TEXT("%s could not be saved"), *Blueprint->GetName());
				return false;
			}
			return true;
		}
	}
}

bool FAttributeWidgetDesignerExporter::HasDesignerContent(const UWidgetBlueprint* Blueprint)
{
	return WidgetWriter::HasDesignerContent(Blueprint);
}

void FAttributeWidgetDesignerExporter::ClearDesignerTree(UWidgetBlueprint* Blueprint)
{
	WidgetWriter::ClearTree(Blueprint);
}

bool FAttributeWidgetDesignerExporter::BuildIntoTree(UUserWidget* Builder)
{
	if (UAttributeLayerPanelWidget* Panel = Cast<UAttributeLayerPanelWidget>(Builder))
	{
		Panel->BuildDefaultLayout();
		return true;
	}
	if (UAttributeListWidget* AttributeList = Cast<UAttributeListWidget>(Builder))
	{
		AttributeList->BuildDefaultLayout();
		return true;
	}
	if (UAttributeAssetListWidget* AssetList = Cast<UAttributeAssetListWidget>(Builder))
	{
		AssetList->BuildDefaultLayout();
		AssetList->ConfigureTileView(); // entry class / size / selection mode on the designer TileView
		return true;
	}
	if (UAttributeAssetItemWidget* AssetItem = Cast<UAttributeAssetItemWidget>(Builder))
	{
		AssetItem->BuildDefaultLayout();
		return true;
	}
	return false;
}

bool FAttributeWidgetDesignerExporter::ExportBlueprint(UWidgetBlueprint* Blueprint, bool bOverwrite, FString& OutMessage)
{
	if (!Blueprint || !Blueprint->WidgetTree || !Blueprint->GeneratedClass)
	{
		OutMessage = TEXT("FAILED: not a compiled Widget Blueprint");
		return false;
	}

	const FString Name = Blueprint->GetName();
	UClass* NativeClass = WidgetWriter::GetNativeParent(Blueprint);

	if (HasDesignerContent(Blueprint) && !bOverwrite)
	{
		OutMessage = FString::Printf(TEXT("%s: skipped (designer tree already has content; use overwrite)"), *Name);
		return false;
	}

	WidgetWriter::CloseEditors(Blueprint);

	Blueprint->Modify();
	Blueprint->WidgetTree->Modify();
	ClearDesignerTree(Blueprint);

	// A throwaway instance (with the blueprint's defaults, e.g. Columns / VisibleRows) builds into the
	// blueprint's own tree: everything it constructs is outered to that tree and saved with the asset.
	UUserWidget* Builder = NewObject<UUserWidget>(GetTransientPackage(), Blueprint->GeneratedClass, NAME_None, RF_Transient);
	Builder->WidgetTree = Blueprint->WidgetTree;
	const bool bBuilt = BuildIntoTree(Builder);
	Builder->WidgetTree = nullptr;
	Builder->MarkAsGarbage();

	if (!bBuilt || !Blueprint->WidgetTree->RootWidget)
	{
		OutMessage = FString::Printf(TEXT("FAILED: %s (parent %s has no C++ layout)"), *Name, *GetNameSafe(NativeClass));
		return false;
	}

	// Bound names become variables; layout-only widgets do not clutter the variable list
	int32 WidgetCount = 0;
	Blueprint->WidgetTree->ForEachWidget([&WidgetCount](UWidget*) { ++WidgetCount; });
	WidgetWriter::MarkBoundWidgetsAsVariables(Blueprint);

	FString Error;
	if (!WidgetWriter::CompileAndSave(Blueprint, Error))
	{
		OutMessage = TEXT("FAILED: ") + Error;
		return false;
	}

	OutMessage = FString::Printf(TEXT("%s: wrote %d widgets"), *Name, WidgetCount);
	return true;
}

int32 FAttributeWidgetDesignerExporter::ExportAll(bool bOverwrite, TArray<FString>& OutLog)
{
	int32 Written = 0;
	for (const TCHAR* Path : AttributeWidgetBlueprints)
	{
		FString Message;
		UWidgetBlueprint* Blueprint = LoadObject<UWidgetBlueprint>(nullptr, Path);
		if (!Blueprint)
		{
			Message = FString::Printf(TEXT("FAILED: %s not found"), Path);
		}
		else if (ExportBlueprint(Blueprint, bOverwrite, Message))
		{
			++Written;
		}

		UE_LOG(LogAttributeWidgetExport, Display, TEXT("%s"), *Message);
		OutLog.Add(Message);
	}
	return Written;
}

int32 UAttributeWidgetDesignerLibrary::ExportAttributeWidgetsToDesigner(bool bOverwrite)
{
	TArray<FString> Log;
	return FAttributeWidgetDesignerExporter::ExportAll(bOverwrite, Log);
}

UAttributeWidgetDesignerExportCommandlet::UAttributeWidgetDesignerExportCommandlet()
{
	IsClient = false;
	IsServer = false;
	IsEditor = true;
	LogToConsole = true;
}

int32 UAttributeWidgetDesignerExportCommandlet::Main(const FString& Params)
{
	TArray<FString> Tokens;
	TArray<FString> Switches;
	ParseCommandLine(*Params, Tokens, Switches);
	const bool bOverwrite = Switches.ContainsByPredicate([](const FString& S) { return S.Equals(TEXT("Overwrite"), ESearchCase::IgnoreCase); });

	TArray<FString> Log;
	const int32 Written = FAttributeWidgetDesignerExporter::ExportAll(bOverwrite, Log);
	const bool bAnyFailed = Log.ContainsByPredicate([](const FString& Line) { return Line.StartsWith(TEXT("FAILED")); });

	UE_LOG(LogAttributeWidgetExport, Display, TEXT("Exported %d widget blueprint(s)%s"), Written, bAnyFailed ? TEXT(", with failures") : TEXT(""));
	return bAnyFailed ? 1 : 0;
}
